from typing import List, Optional, Dict
from pydantic import BaseModel, Field


class AlternativePrediction(BaseModel):
    class_name: str
    probability: float


class DiseasePredictionResponse(BaseModel):
    is_valid_plant: bool = True
    predicted_class: str
    crop_name: str
    condition: str  # Disease name or "Healthy"
    confidence: float
    confidence_level: str  # "High", "Moderate", "Low"
    top_alternatives: List[AlternativePrediction]
    gradcam_heatmap_base64: Optional[str] = None
    symptoms_overview: Optional[str] = None
    management_practices: List[str] = []
    model_name: str = "MobileNetV2-TransferLearning"
    model_version: str = "1.0.0"
    academic_reference: str = (
        "Based on comparative transfer learning methodology presented by "
        "Wubetu Barud Demilie (2024), Journal of Big Data, 11:71."
    )
    disclaimer: str = (
        "CRITICAL ADVISORY: This diagnosis is generated by an automated deep learning model "
        "for research and preliminary screening purposes. Do NOT apply chemical fungicides or "
        "pesticides without on-field validation by an ANGRAU / ICAR certified plant pathologist."
    )
