"""
AgriAI - Module 11: Reports and Downloads
Generates downloadable analytical summaries, prediction logs, and audit reports.
"""

import streamlit as st
import pandas as pd
from datetime import datetime

from app.components.theme import apply_saas_theme, render_sidebar, render_top_bar
from app.components.cards import render_page_header
from app.components.header import render_disclaimer
from app.utils.api_client import api_client

st.set_page_config(page_title="Reports & Downloads | AgriAI", page_icon="📑", layout="wide")
apply_saas_theme()
render_sidebar()
render_top_bar(current_district="Andhra Pradesh")

render_page_header(
    title="Agricultural Reports & Data Exports",
    subtitle="Generate formatted audit summaries, historical time-series extracts, and agronomic reports with generated timestamps and metadata.",
    category_tag="DATA GOVERNANCE & EXPORTS",
)

st.markdown('<div class="saas-card">', unsafe_allow_html=True)
st.markdown("<h4 style='margin-top:0; color:#0f172a; font-weight:700;'>📝 Report Generator Configuration</h4>", unsafe_allow_html=True)
col_r1, col_r2 = st.columns(2)

with col_r1:
    report_type = st.selectbox(
        "Select Report Template",
        [
            "Crop Production & Yield Performance Report",
            "Mandi Wholesale Market Price Audit",
            "Meteorological & Agro-Climatic Summary",
            "Soil Health & Nutrient Classification Report",
        ],
    )
with col_r2:
    district_sel = st.selectbox("Focus District", ["All"] + [
        "Guntur", "Krishna", "Kurnool", "Anantapur", "East Godavari", "Chittoor", "Prakasam"
    ])

generate_btn = st.button("Generate Formatted Audit Report", type="primary")
st.markdown('</div>', unsafe_allow_html=True)

if generate_btn:
    gen_time = datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")

    st.markdown('<div class="saas-card">', unsafe_allow_html=True)
    st.markdown(
        f"""
        <div style="border-bottom: 2px solid #16a34a; padding-bottom: 12px; margin-bottom: 16px;">
            <span style="font-size:0.75rem; text-transform:uppercase; font-weight:700; color:#16a34a;">Official System Extract</span>
            <h2 style="margin:4px 0 6px 0; color:#0f172a; font-weight:800;">{report_type}</h2>
            <div style="font-size:0.85rem; color:#64748b;">
                Generated: <b>{gen_time}</b> • Region: <b>Andhra Pradesh ({district_sel})</b> • Platform: <b>AgriAI v1.0.0</b>
            </div>
        </div>
        """,
        unsafe_allow_html=True,
    )

    if "Crop Production" in report_type:
        records = api_client.get_crop_production(district=district_sel)
        source = "Directorate of Economics & Statistics (DES) / data.gov.in"
    elif "Mandi" in report_type:
        records = api_client.get_mandi_prices(district=district_sel)
        source = "AGMARKNET Wholesale Trade Statistics"
    elif "Meteorological" in report_type:
        records = api_client.get_weather(district=district_sel)
        source = "India Meteorological Department (IMD) / Open-Meteo"
    else:
        records = api_client.get_soil(district=district_sel)
        source = "Department of Agriculture - Soil Health Card Portal"

    st.caption(f"Authority Data Source: {source}")

    if records:
        df_rep = pd.DataFrame(records)
        st.dataframe(df_rep, use_container_width=True, height=300)

        csv_bytes = df_rep.to_csv(index=False).encode("utf-8")
        st.download_button(
            label="📥 Download Complete Report Dataset (CSV)",
            data=csv_bytes,
            file_name=f"agriai_report_{datetime.utcnow().strftime('%Y%m%d_%H%M')}.csv",
            mime="text/csv",
        )
    else:
        st.warning("No records found matching the specified report filters.")

    st.markdown('</div>', unsafe_allow_html=True)

render_disclaimer(
    "Official extracts generated by AgriAI for agricultural planning, research, and extension advisory purposes. "
    "Commercial spot transactions should be confirmed with respective APMC mandi secretariats."
)
